CREATE EXTENSION IF NOT EXISTS postGIS;

CREATE TABLE IF NOT EXISTS users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    allow_login BOOLEAN NOT NULL DEFAULT TRUE,
    username TEXT UNIQUE NOT NULL,
    name TEXT,
    surname TEXT,
    profile_url TEXT,
    description TEXT,
    create_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivate_timestamp TIMESTAMP,
    last_update_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS passwords (
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE PRIMARY KEY,
    hash TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS password_reset_requests (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS register_methods (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_register_methods (
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    method_id INT NOT NULL REFERENCES register_methods(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, method_id)
);

CREATE TABLE IF NOT EXISTS login_history (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    method TEXT NOT NULL,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    success BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS user_settings (
    user_id INT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    email_notifications BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS user_push_subscriptions (
    endpoint TEXT PRIMARY KEY,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    auth TEXT NOT NULL,
    p256dh TEXT NOT NULL
);


CREATE TABLE IF NOT EXISTS permissions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_permissions (
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    permission_id INT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    read BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (user_id, permission_id)
);

CREATE TABLE IF NOT EXISTS user_groups (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT
);

CREATE TABLE IF NOT EXISTS group_permissions (
    group_id INT NOT NULL REFERENCES user_groups(id) ON DELETE CASCADE,
    permission_id INT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    allow BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (group_id, permission_id)
);

CREATE TABLE IF NOT EXISTS user_group_assignments (
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    group_id INT NOT NULL REFERENCES user_groups(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, group_id)
);


CREATE TABLE IF NOT EXISTS event_categories (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);


CREATE TABLE IF NOT EXISTS events (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT,
    start_timestamp TIMESTAMP,
    end_timestamp TIMESTAMP,
    location_name TEXT,
    location GEOGRAPHY(POINT, 4326),
    seating INT,
    state TEXT NOT NULL DEFAULT 'upcoming',
    CONSTRAINT check_event_state CHECK (state IN ('upcoming', 'active', 'complete', 'canceled')),
		allow_unregistered BOOLEAN NOT NULL DEFAULT FALSE,
    draft BOOLEAN NOT NULL DEFAULT TRUE,
    subscriber_group INT REFERENCES user_groups(id) ON DELETE SET NULL,
		CONSTRAINT chk_draft CHECK (
			(draft IS TRUE) OR 
			(draft is FALSE 
			AND description IS NOT NULL 
			AND start_timestamp IS NOT NULL 
			AND end_timestamp IS NOT NULL 
			AND location_name IS NOT NULL 
			AND location IS NOT NULL)
    )
);


CREATE OR REPLACE FUNCTION auto_create_event_subscriber_group()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.subscriber_group IS NULL THEN
        INSERT INTO user_groups (description)
        VALUES ('Subscriber group for event: ' || NEW.title)
        RETURNING id INTO NEW.subscriber_group;
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_auto_create_event_group
BEFORE INSERT ON events
FOR EACH ROW
EXECUTE FUNCTION auto_create_event_subscriber_group();

CREATE TABLE IF NOT EXISTS event_category_associations (
    event_id INT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    category_id INT NOT NULL REFERENCES event_categories(id) ON DELETE CASCADE,
    PRIMARY KEY (event_id, category_id)
);

CREATE TABLE IF NOT EXISTS event_attendance_register_methods (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS event_attendances (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    user_id INT REFERENCES users(id) ON DELETE SET NULL, 
    name TEXT,  
    surname TEXT,
    register_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    register_method_id INT NOT NULL REFERENCES event_attendance_register_methods(id),
    reserve BOOLEAN NOT NULL DEFAULT FALSE,
    canceled BOOLEAN NOT NULL DEFAULT FALSE,
    join_timestamp TIMESTAMP,
		CONSTRAINT chk_attendance_identity CHECK (
        (user_id IS NOT NULL) OR (name IS NOT NULL AND surname IS NOT NULL)
    )
);


CREATE TABLE IF NOT EXISTS notifications (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    title TEXT NOT NULL,
    detail TEXT
);

CREATE TABLE IF NOT EXISTS user_notifications (
    notification_id INT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    read BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (notification_id, user_id)
);